import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import { prisma } from '@/lib/db';
import { practiceReport, reportCsv } from '@/lib/practice-reports';
import { practiceFinancialDocument } from '@/lib/practice-documents';
import { issuePracticeInvoice, recordPracticeReceipt, savePracticePayer, proposePracticeAdjustment, reviewPracticeAdjustment } from '@/lib/practice-finance';
import { PDFDocument } from 'pdf-lib';
const database = new URL(process.env.DATABASE_URL || 'postgresql://localhost/undefined');
assert.equal(database.pathname, '/pax_practice_test'); assert.ok(['127.0.0.1', 'localhost'].includes(database.hostname));
process.env.PRACTICE_WORKSPACE_ENABLED = 'true';
test('reports count receipts once, keep credits separate, filter source services and protect PDF access', async () => {
  try {
    const suffix = randomUUID();
    const owner = await prisma.user.create({ data: { name: 'Report Owner', email: `${suffix}@example.test`, role: 'PRACTITIONER', tier: 'TIER2_PROFESSIONAL', hubMember: true } });
    const workspace = await prisma.practiceWorkspace.create({ data: { ownerId: owner.id } });
    const reception = await prisma.user.create({ data: { name: 'Reception', email: `reception-${suffix}@example.test`, role: 'STAFF' } });
    await prisma.practiceMember.create({ data: { workspaceId: workspace.id, userId: reception.id, roles: ['RECEPTION'] } });
    const payer = await savePracticePayer(owner.id, workspace.id, { kind: 'OTHER', name: 'Test payer' });
    const now = new Date();
    const services = await Promise.all(['CONSULTATION', 'FOLLOWUP'].map((serviceCode) => prisma.practiceService.create({ data: { workspaceId: workspace.id, sourceKey: `${suffix}:${serviceCode}`, description: serviceCode, serviceCode, serviceDate: now, amountMinor: 10000, rateSnapshot: {} } })));
    const invoice = await issuePracticeInvoice(owner.id, workspace.id, { requestKey: randomUUID(), serviceIds: services.map((s) => s.id), payers: [{ payerId: payer.id, amountMinor: 20000 }] });
    const invoicePayer = await prisma.practiceInvoicePayer.findFirstOrThrow({ where: { invoiceId: invoice.id } });
    const receipt = await recordPracticeReceipt(owner.id, workspace.id, { requestKey: randomUUID(), payerId: payer.id, amountMinor: 25000, receivedAt: now.toISOString(), method: 'MPESA', allocations: [{ invoicePayerId: invoicePayer.id, amountMinor: 20000 }] });
    const filters = { from: new Date(now.getTime() - 86400000).toISOString(), to: new Date(now.getTime() + 86400000).toISOString() };
    const report = await practiceReport(owner.id, workspace.id, filters);
    assert.equal(report.totals.cashReceivedMinor, 25000); assert.equal(report.totals.invoicedMinor, 20000); assert.equal(report.totals.creditMinor, 5000); assert.equal(report.totals.outstandingMinor, 0);
    assert.equal(report.statement.openingMinor, 0); assert.equal(report.statement.closingDatedMinor, -5000);
    const filtered = await practiceReport(owner.id, workspace.id, { ...filters, service: 'FOLLOWUP' });
    assert.equal(filtered.totals.invoicedMinor, 10000); assert.equal(filtered.totals.attributedCashMinor, 10000); assert.equal(filtered.totals.cashReceivedMinor, 0);
    assert.equal(report.rows.filter((r) => r.type === 'RECEIPT').length, 1);
    assert.ok(reportCsv(report).includes('250.00'));
    await assert.rejects(practiceFinancialDocument(reception.id, workspace.id, 'invoice', invoice.id), /access/);
    const pdf = await practiceFinancialDocument(owner.id, workspace.id, 'invoice', invoice.id);
    assert.ok((await PDFDocument.load(pdf)).getPageCount() > 0);
    const receiptPdf = await practiceFinancialDocument(owner.id, workspace.id, 'receipt', receipt.id);
    assert.ok((await PDFDocument.load(receiptPdf)).getPageCount() > 0);
    const reversal = await proposePracticeAdjustment(owner.id, workspace.id, { requestKey: randomUUID(), kind: 'RECEIPT_REVERSAL', receiptId: receipt.id, reason: 'Duplicate bank receipt recorded' });
    await reviewPracticeAdjustment(owner.id, workspace.id, { id: reversal.id, decision: 'APPROVED', reason: 'Bank evidence confirms duplicate' });
    const reversed = await practiceReport(owner.id, workspace.id, filters);
    assert.equal(reversed.totals.cashReceivedMinor, 25000, 'Original cash activity remains visible');
    assert.equal(reversed.totals.receiptReversalsMinor, 25000);
    assert.ok(reportCsv(reversed).includes('"-250.00"'), 'Negative financial values remain numeric CSV cells');
    assert.equal(reversed.totals.creditMinor, 0);
    assert.equal(reversed.totals.outstandingMinor, 20000);
    assert.equal(reversed.rows.filter((r) => r.type === 'RECEIPT').length, 1);
    const voidRequest = await proposePracticeAdjustment(owner.id, workspace.id, { requestKey: randomUUID(), kind: 'VOID', invoiceId: invoice.id, reason: 'Invoice issued in error' });
    await reviewPracticeAdjustment(owner.id, workspace.id, { id: voidRequest.id, decision: 'APPROVED', reason: 'Confirmed invoice should be void' });
    const voided = await practiceReport(owner.id, workspace.id, filters);
    assert.equal(voided.totals.invoicedMinor, 20000, 'Issued document history remains visible');
    assert.equal(voided.totals.voidedMinor, 20000);
    assert.equal(voided.totals.outstandingMinor, 0);
    assert.equal(voided.statement.closingDatedMinor, 0);
  } finally { await prisma.$disconnect(); }
});
